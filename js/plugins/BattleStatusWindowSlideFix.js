/*:
 * @plugindesc 전투 시작 시 상태창(액터 얼굴/HP 나열된 창)이 왼쪽에서
 * 오른쪽으로 슬라이드하며 이동하는 기본 MV 연출을 제거합니다.
 * @author Custom
 *
 * @help
 * ============================================================================
 * 설명
 * ============================================================================
 * 기본 RPG Maker MV 코어(rpg_scenes.js)는 전투 시작 시 매 프레임마다
 * Scene_Battle.prototype.updateWindowPositions()를 호출해서, 상태창을
 * x=0에서 시작해 (파티 커맨드 창 너비, 혹은 그 절반) 위치까지 조금씩
 * (프레임당 16px)씩 오른쪽으로 밀어 넣는 연출을 합니다. 입력 가능 여부
 * (BattleManager.isInputting())에 따라 목표 위치가 또 한 번 바뀌면서
 * 두 번 밀리기도 합니다.
 *
 * 파티 커맨드 창을 안 쓰거나 숨겨놓은 프로젝트에서는 이 연출이 그냥
 * "전투 시작하자마자 상태창이 오른쪽으로 슥 움직이는" 것처럼만 보이므로,
 * 이 플러그인은 그 슬라이드를 제거하고 상태창이 처음부터 최종 위치에
 * 바로 나타나게 합니다.
 *
 * ============================================================================
 * 플러그인 순서
 * ============================================================================
 * 다른 전투 UI 관련 플러그인들보다 아래(맨 아래쪽)에 두세요.
 *
 * ============================================================================
 * 이용 약관
 * ============================================================================
 * 자유롭게 수정 및 사용 가능합니다.
 */

(function() {
    'use strict';

    // 코어의 updateWindowPositions()를 통째로 덮어써서, 슬라이드 없이
    // 바로 최종 위치에 고정시킵니다. (원본은 statusX를 향해 프레임당
    // 16px씩 움직였지만, 여기서는 즉시 그 값으로 맞춥니다.)
    // 파티 커맨드 창 폭 기준이 아니라, 화면 정중앙에 고정합니다.
    Scene_Battle.prototype.updateWindowPositions = function() {
        this._statusWindow.x = (Graphics.boxWidth - this._statusWindow.width) / 2;
    };

})();
