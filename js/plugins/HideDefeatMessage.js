/*:
 * @plugindesc 적에게 패배(전멸)했을 때 기본으로 뜨는 "패배했습니다" 대사창을 띄우지 않습니다.
 * @author ㄹㅅㅁ
 *
 * @help
 * ============================================================================
 * 개요
 * ============================================================================
 * RPG 만들기 MV 기본 시스템은 파티가 전멸하면 BattleManager.processDefeat
 * 에서 데이터베이스 [시스템 > 용어 > 패배] 텍스트를 메시지 창으로 띄운
 * 뒤에 게임오버(또는 전투 이벤트의 "패배" 페이지)로 넘어갑니다.
 *
 * 이 플러그인은 그 메시지 출력 부분만 제거합니다. 그 외 패배 처리
 * (BGM 정지, 패배 ME 재생, 게임오버 전환, endBattle 호출 등)는
 * 원본 그대로 동작합니다.
 *
 * (이전 버전은 processDefeat 전체를 새로 작성하면서 endBattle(2) 호출이
 * 빠져있었습니다. 그 때문에 전투가 절대 안 끝나고 패배 화면에서 멈추는
 * 문제가 있었습니다. 이번 버전은 displayDefeatMessage만 비활성화하는
 * 방식으로 수정해서 원본 흐름을 그대로 보존합니다.)
 *
 * 플러그인 매니저에서 다른 전투 관련 플러그인(YEP_BattleEngineCore 등)
 * 아래쪽에 두시면 됩니다.
 *
 * ============================================================================
 * 라이선스
 * ============================================================================
 * 자유롭게 사용, 수정하실 수 있습니다.
 */

var Imported = Imported || {};
Imported.HideDefeatMessage = true;

(function () {
  'use strict';

  // 패배 메시지 창만 띄우지 않도록 합니다. 그 외 로직(playDefeatMe,
  // replayBgmAndBgs/stopBgm, endBattle(2) 호출 등)은 원본 processDefeat가
  // 그대로 수행하므로 전투 종료 처리가 정상적으로 이어집니다.
  BattleManager.displayDefeatMessage = function () {
    // 원래 여기서 $gameMessage.add(TextManager.defeat)를 호출했지만,
    // 아무것도 하지 않게 해서 대사창이 나오지 않게 했습니다.
  };
})();
