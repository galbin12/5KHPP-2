/*:
 * @plugindesc 전투 시작 시 액터가 중앙(또는 다른 위치)에서 슬라이드하며
 * 오른쪽(홈 위치)으로 이동하는 연출을 제거하고 바로 홈 위치에 배치합니다.
 * @author Custom
 *
 * @help
 * ============================================================================
 * 설명
 * ============================================================================
 * 기본 RPG Maker MV는 전투 시작 시 Sprite_Actor.moveToStartPosition()에서
 * 홈 위치 기준으로 오프셋을 준 뒤 슬라이드해 들어오는 연출을 합니다.
 * (프론트뷰 상태창 사용 시 "화면 중앙에 있다가 오른쪽으로 이동"하는 것처럼
 * 보이는 현상이 바로 이것입니다.)
 *
 * 이 플러그인은 그 슬라이드 오프셋을 0으로 만들어서, 액터 스프라이트가
 * 처음부터 자신의 홈 위치(setActorHome에서 계산된 위치)에 바로 나타나게
 * 합니다.
 *
 * ============================================================================
 * 플러그인 순서
 * ============================================================================
 * YEP_BattleEngineCore, YEP_BattleStatusWindow 보다 아래에 두세요.
 * (Sprite_Actor.setActorHome 자체는 건드리지 않고 moveToStartPosition만
 * 덮어쓰기 때문에 순서에 크게 민감하지는 않습니다.)
 *
 * ============================================================================
 * 이용 약관
 * ============================================================================
 * 자유롭게 수정 및 사용 가능합니다.
 */

(function() {
    'use strict';

    // 기본 코어: this.startMove(300, 0, 0) 형태로 홈 위치에서 +300px 어긋난
    // 지점에 즉시 배치한 뒤, 이후 updateMove()에서 홈 위치로 서서히 이동시켜
    // "슬라이드 인" 효과를 만듭니다. 오프셋을 0으로 주면 애초에 어긋난 위치에
    // 놓이지 않으므로 슬라이드 자체가 사라집니다.
    Sprite_Actor.prototype.moveToStartPosition = function() {
        this.startMove(0, 0, 0);
    };

})();
